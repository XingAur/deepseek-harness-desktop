/**
 * Isolated native window managing scheduled tasks: task list, three-mode
 * schedule input, next-run preview, and immediate controls. Renderer actions
 * arrive through the local scheme; state flows back as CustomEvents.
 */

import type { BrowserWindow } from 'electron'
import { fileURLToPath } from 'node:url'
import { auxiliaryWindowChromeOptions, auxiliaryWindowHasCustomFrame } from './auxiliary-window-options.ts'
import { revealApplication } from './electron-reveal.ts'
import { createDesktopLocalWindow } from './local-window-policy.ts'
import type { DesktopLocale } from './runtime.ts'
import { taskEditorCopy } from './task-editor-copy.ts'

const TASK_EDITOR_SCHEME = 'dsh-task-editor:'
const MAX_TEXT_QUERY_BYTES = 4096
const TASK_EDITOR_DOCUMENT = fileURLToPath(new URL('./native-ui/task-editor.html', import.meta.url))

/** Host-side gateway the window drives; the scheduler row supplies it. */
export interface TaskEditorWindowGateway {
  /** Complete management snapshot for the current render. */
  list(): Promise<TaskEditorSnapshot>
  /** Validate and persist one task payload; rejects with a localized message key. */
  upsert(task: unknown): Promise<unknown>
  /** Remove one task. */
  remove(id: string): Promise<void>
  /** Trigger one task immediately; false when the task is unknown or paused. */
  runNow(id: string): Promise<boolean>
  /** Toggle one task between enabled and paused. */
  setEnabled(id: string, enabled: boolean): Promise<boolean>
  /** Next three trigger instants (ISO strings) of one schedule rule. */
  preview(schedule: unknown): Promise<string[]>
  /** Interpret one sentence as a cron expression; `null` degrades to manual entry. */
  interpretSchedule(text: string): Promise<{ expression: string } | null>
  /** Native workspace-directory chooser; `null` when cancelled. */
  pickDirectory(): Promise<string | null>
}

/** Data payload pushed into the renderer. */
export interface TaskEditorSnapshot {
  readonly tasks: readonly unknown[]
  readonly runs: Record<string, readonly unknown[]>
  readonly presets: readonly string[]
}

/** Renderer actions parsed from one local navigation. */
export type TaskEditorAction =
  | { readonly action: 'close' }
  | { readonly action: 'submit'; readonly task: string }
  | { readonly action: 'remove'; readonly id: string }
  | { readonly action: 'run'; readonly id: string }
  | { readonly action: 'enable'; readonly id: string; readonly enabled: boolean }
  | { readonly action: 'preview'; readonly schedule: string }
  | { readonly action: 'interpret'; readonly text: string }
  | { readonly action: 'pick-directory' }

/** Parse only the actions generated by the local task-editor document. */
export function parseTaskEditorAction(href: string): TaskEditorAction | undefined {
  let url: URL
  try { url = new URL(href) } catch { return undefined }
  if (url.protocol !== TASK_EDITOR_SCHEME
    || url.username !== '' || url.password !== '' || url.port !== ''
    || url.pathname !== '' || url.hash !== '') return undefined
  const action = url.hostname
  const first = (key: string): string | null => {
    const keys = [...url.searchParams.keys()]
    if (keys.length !== 1 || keys[0] !== key) return null
    return url.searchParams.get(key)
  }
  if (action === 'close' && [...url.searchParams.keys()].length === 0) return { action }
  if (action === 'submit' || action === 'preview') {
    const payload = first(action === 'submit' ? 'task' : 'schedule')
    if (payload === null || Buffer.byteLength(payload, 'utf8') > MAX_TEXT_QUERY_BYTES) return undefined
    return action === 'submit' ? { action, task: payload } : { action: 'preview', schedule: payload }
  }
  if (action === 'remove' || action === 'run') {
    const id = first('id')
    if (id === null || id === '' || Buffer.byteLength(id, 'utf8') > 256) return undefined
    return { action, id }
  }
  if (action === 'enable') {
    const keys = [...url.searchParams.keys()].sort().join(',')
    if (keys !== 'enabled,id') return undefined
    const id = url.searchParams.get('id')
    if (id === null || id === '' || Buffer.byteLength(id, 'utf8') > 256) return undefined
    return { action, id, enabled: url.searchParams.get('enabled') === '1' }
  }
  if (action === 'interpret') {
    const text = first('text')
    if (text === null || text.trim() === '' || Buffer.byteLength(text, 'utf8') > MAX_TEXT_QUERY_BYTES) {
      return undefined
    }
    return { action, text }
  }
  if (action === 'pick-directory' && [...url.searchParams.keys()].length === 0) {
    return { action }
  }
  return undefined
}

export interface TaskEditorWindowOptions {
  readonly locale: DesktopLocale
  readonly gateway: TaskEditorWindowGateway
}

/** Own one isolated task-editor window; repeated opens focus the same instance. */
export class TaskEditorWindow {
  private window: BrowserWindow | undefined
  private disposed = false

  constructor(private readonly options: TaskEditorWindowOptions) {}

  open(): void {
    const existing = this.window
    if (existing !== undefined && !existing.isDestroyed()) {
      revealApplication(existing)
      void this.pushState()
      return
    }
    this.disposed = false
    const window = createDesktopLocalWindow({
      partition: 'dsh-task-editor',
      title: taskEditorCopy(this.options.locale).title,
      ...auxiliaryWindowChromeOptions(),
      width: 720,
      height: 640,
      minWidth: 640,
      minHeight: 520,
      show: false,
      autoHideMenuBar: true,
      backgroundColor: '#202124',
    })
    this.window = window
    window.removeMenu()
    const navigate = (event: Electron.Event, href: string): void => {
      const action = parseTaskEditorAction(href)
      event.preventDefault()
      if (action !== undefined) void this.handleAction(action)
    }
    window.webContents.on('will-navigate', navigate)
    window.webContents.on('will-redirect', navigate)
    window.once('ready-to-show', () => {
      if (!this.disposed && this.window === window && !window.isDestroyed()) revealApplication(window)
    })
    window.on('closed', () => {
      if (this.window === window) this.window = undefined
    })
    void window.loadFile(TASK_EDITOR_DOCUMENT, {
      query: {
        locale: this.options.locale,
        platform: process.platform,
        frame: String(auxiliaryWindowHasCustomFrame()),
      },
    }).then(() => {
      void this.pushState()
    }).catch(() => {
      if (!this.disposed && this.window === window) window.close()
    })
  }

  close(): void {
    this.disposed = true
    const window = this.window
    this.window = undefined
    if (window !== undefined && !window.isDestroyed()) window.close()
  }

  /** Push one complete management snapshot into the renderer. */
  async pushState(): Promise<void> {
    const window = this.window
    if (window === undefined || window.isDestroyed()) return
    try {
      const snapshot = await this.options.gateway.list()
      await window.webContents.executeJavaScript(
        `window.dispatchEvent(new CustomEvent('dsh-task-editor-state', { detail: ${JSON.stringify(snapshot)} }))`,
        true,
      )
    } catch {
      // A transient gateway failure keeps the last rendered state.
    }
  }

  private async emit(event: string, detail: unknown): Promise<void> {
    const window = this.window
    if (window === undefined || window.isDestroyed()) return
    await window.webContents.executeJavaScript(
      `window.dispatchEvent(new CustomEvent(${JSON.stringify(event)}, { detail: ${JSON.stringify(detail)} }))`,
      true,
    ).catch(() => {})
  }

  private async handleAction(action: TaskEditorAction): Promise<void> {
    const gateway = this.options.gateway
    switch (action.action) {
      case 'close': {
        this.close()
        return
      }
      case 'submit': {
        try {
          await gateway.upsert(JSON.parse(action.task) as unknown)
          await this.pushState()
          await this.emit('dsh-task-editor-saved', { ok: true })
        } catch (cause: unknown) {
          await this.emit('dsh-task-editor-saved', {
            ok: false,
            error: cause instanceof Error ? cause.message : String(cause),
          })
        }
        return
      }
      case 'remove': {
        await gateway.remove(action.id).catch(() => {})
        await this.pushState()
        return
      }
      case 'run': {
        const started = await gateway.runNow(action.id).catch(() => false)
        await this.emit('dsh-task-editor-run', { ok: started })
        return
      }
      case 'enable': {
        await gateway.setEnabled(action.id, action.enabled).catch(() => false)
        await this.pushState()
        return
      }
      case 'preview': {
        try {
          const next = await gateway.preview(JSON.parse(action.schedule) as unknown)
          await this.emit('dsh-task-editor-preview', { ok: true, next })
        } catch (cause: unknown) {
          await this.emit('dsh-task-editor-preview', {
            ok: false,
            error: cause instanceof Error ? cause.message : String(cause),
          })
        }
        return
      }
      case 'interpret': {
        const result = await gateway.interpretSchedule(action.text).catch(() => null)
        await this.emit('dsh-task-editor-interpret', { result })
        return
      }
      case 'pick-directory': {
        const directory = await this.options.gateway.pickDirectory().catch(() => null)
        await this.emit('dsh-task-editor-directory', { directory })
        return
      }
    }
  }
}
